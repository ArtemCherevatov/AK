#!/bin/bash

FILE="random_numbers.txt"

# Очищуємо файл перед записом (або створюємо новий)
> "$FILE"

echo "=== Згенеровані числа ==="
# Генеруємо 5 випадкових додатних чисел (від 1 до 1000) і записуємо у файл
for i in {1..5}; do
    NUM=$((RANDOM % 1000 + 1))
    echo "$NUM" >> "$FILE"
done

# Виводимо вміст файлу на екран
cat "$FILE"

# Знаходимо найменше число (сортуємо як числа і беремо перший рядок)
MIN_NUM=$(sort -n "$FILE" | head -n 1)

# Перезаписуємо файл, залишаючи лише найменше число
echo "$MIN_NUM" > "$FILE"

echo "=== Результат ==="
echo "Найменше число: $MIN_NUM"
echo "Оновлений вміст файлу $FILE:"
cat "$FILE"
